def save_checkpoint(model_obj, optimizer, epoch, val_loss, path):
    torch.save({
        "epoch":      epoch,
        "model":      model_obj.state_dict(),
        "optimizer":  optimizer.state_dict(),
        "val_loss":   val_loss,
    }, path)
    print(f"  ✓ Checkpoint saved: {path}")


