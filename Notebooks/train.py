_orig_vit_forward = model.vit.vit.encoder.forward

def _checkpointed_vit_encoder_forward(self, x):
    layers = list(self.layers)
    x = checkpoint_sequential(layers, segments=len(layers) // 2,
                               input=x, use_reentrant=False)
    return self.ln(x)

import types
model.vit.vit.encoder.forward = types.MethodType(
    _checkpointed_vit_encoder_forward, model.vit.vit.encoder
)
