# GPU Selection — pick the GPU with most free memory
# Uses nvidia-smi so it sees ALL users' processes, not just ours.
# ─────────────────────────────────────────────
def _pick_best_gpu():
    """Return the GPU index with the most free memory (via nvidia-smi), or 0."""
    if not torch.cuda.is_available():
        return None
    n = torch.cuda.device_count()
    try:
        import subprocess
        result = subprocess.run(
            ["nvidia-smi",
             "--query-gpu=index,memory.free,memory.total,name",
             "--format=csv,noheader,nounits"],
            capture_output=True, text=True, timeout=10
        )
        free_mem = {}
        for line in result.stdout.strip().splitlines():
            idx, free, total, name = [x.strip() for x in line.split(",")]
            idx = int(idx)
            free_mb = int(free)
            total_mb = int(total)
            print(f"  GPU {idx} [{name}]: {free_mb} MiB free / {total_mb} MiB total")
            free_mem[idx] = free_mb
        best = max(free_mem, key=free_mem.get)
        print(f"  → Selected GPU {best} ({free_mem[best]} MiB free)")
        return best
    except Exception as e:
        print(f"  [WARN] nvidia-smi failed ({e}), defaulting to GPU 0")
        return 0

