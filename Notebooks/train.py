epochs_s3 = 5
best_val_loss_s3 = float("inf")
best_val_auc_s3  = 0.0
patience_s3 = 3
no_improve_s3 = 0

print("\n" + "="*60)
print("STAGE 3: Fine-Tune Full Multi-Modal Pipeline")
print("="*60)

for param in model.vit.parameters():
    param.requires_grad = True

# Lower LR for fine-tuning; use differential LR
optimizer3 = optim.AdamW([
    {"params": model.vit.parameters(),      "lr": 1e-5},
    {"params": model.temporal.parameters(), "lr": 5e-5},
    {"params": model.frequency.parameters(),"lr": 5e-5},
    {"params": model.audio.parameters(),    "lr": 5e-5},
    {"params": model.classifier.parameters(),"lr": 1e-4},
], weight_decay=1e-4)

scheduler3 = optim.lr_scheduler.CosineAnnealingLR(optimizer3, T_max=epochs_s3)
scaler3    = GradScaler('cuda')

for epoch in range(epochs_s3):
    print(f"\n── S3 Epoch {epoch+1}/{epochs_s3} ──")
    train_epoch(model, train_loader, optimizer3, scaler3,
                criterion, device, f"S3 Epoch {epoch+1}", is_frame_level=False)
    val_loss, val_acc, val_f1, val_auc = evaluate(
        model, val_loader, criterion, device, is_frame_level=False)

    scheduler3.step()

    # Save on best AUC (more meaningful than loss for imbalanced data)
    if val_auc > best_val_auc_s3:
        best_val_auc_s3 = val_auc
        no_improve_s3  = 0
        save_checkpoint(model, optimizer3, epoch, val_loss,
                        "models/best_stage3.pth")
    else:
        no_improve_s3 += 1
        if no_improve_s3 >= patience_s3:
            print(f"  Early stopping S3 at epoch {epoch+1}")
            break

    torch.cuda.empty_cache()
    print_gpu_memory(f"S3 epoch {epoch+1} end")


