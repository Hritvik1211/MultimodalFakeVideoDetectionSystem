# ─────────────────────────────────────────────
# Frame-Level Wrapper (Stage 1)
# ─────────────────────────────────────────────
class FrameLevelViT(nn.Module):
    """Trains the ViT backbone independently on single frames."""
    def __init__(self, vit_extractor, dropout=0.3):
        super().__init__()
        self.vit = vit_extractor
        self.classifier = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(self.vit.embed_dim, 1)
        )

    def forward(self, x):
        emb = self.vit(x)
        return self.classifier(emb)


# ─────────────────────────────────────────────
# Training / Eval helpers
# ─────────────────────────────────────────────
def train_epoch(model_obj, loader, optimizer, scaler, criterion_obj,
                device_obj, stage_name, is_frame_level=False,
                accum_steps=ACCUM_STEPS):
    model_obj.train()
    running_loss = 0.0
    correct = 0
    total   = 0
    all_labels = []
    all_probs  = []

    optimizer.zero_grad(set_to_none=True)
    pbar = tqdm(loader, desc=f"Training {stage_name}")

    for step, batch in enumerate(pbar):
        rgb   = batch["rgb"].to(device_obj, non_blocking=True)
        label = batch["label"].to(device_obj, non_blocking=True).unsqueeze(1)

        # ── Label Smoothing ───────────────────────
        smoothed_label = label * 0.9 + 0.05 # 1.0 -> 0.95, 0.0 -> 0.05
        
        # ── Gradient Accumulation ─────────────────
        # Divide loss by accum_steps so gradients average over the
        # effective batch (micro_batch × accum_steps) not just micro_batch.
        with autocast('cuda'):
            if is_frame_level:
                S = rgb.shape[1]
                frame_idx = torch.randint(0, S, (1,)).item()
                outputs = model_obj(rgb[:, frame_idx])
                loss = criterion_obj(outputs, smoothed_label) / accum_steps
            else:
                fft   = batch["fft"].to(device_obj, non_blocking=True)
                audio = batch["audio"].to(device_obj, non_blocking=True)
                audio_mask = batch.get("audio_missing")
                if audio_mask is not None:
                    audio_mask = audio_mask.to(device_obj, non_blocking=True)
                    
                outputs, embs = model_obj(rgb, fft, audio, audio_mask=audio_mask, return_embeddings=True)
                
                loss_bce = criterion_obj(outputs, smoothed_label)
                
                # Consistency Loss
                e_vid, e_fft, e_aud = embs
                cos = nn.CosineSimilarity(dim=-1)
                
                loss_consist = (1 - cos(e_vid, e_fft)).mean()
                if audio_mask is not None:
                    valid_audio = ~audio_mask
                    if valid_audio.any():
                        loss_consist += (1 - cos(e_vid[valid_audio], e_aud[valid_audio])).mean()
                else:
                    loss_consist += (1 - cos(e_vid, e_aud)).mean()
                    
                loss = (loss_bce + 0.1 * loss_consist) / accum_steps

        scaler.scale(loss).backward()

        is_update_step = ((step + 1) % accum_steps == 0) or (step + 1 == len(loader))
        if is_update_step:
            scaler.unscale_(optimizer)
            torch.nn.utils.clip_grad_norm_(model_obj.parameters(), max_norm=1.0)
            scaler.step(optimizer)
            scaler.update()
            optimizer.zero_grad(set_to_none=True)
            # Free intermediate activations after each optimiser update
            torch.cuda.empty_cache()

        # ── Track metrics (use un-scaled loss for display) ──
        loss = loss * accum_steps  # rescale back for logging

        bs = label.size(0)
        running_loss += loss.item() * bs
        probs  = torch.sigmoid(outputs).detach()
        preds  = (probs > 0.5).float()
        correct += (preds == label).sum().item()
        total   += bs

        all_labels.extend(label.cpu().numpy().flatten().tolist())
        all_probs.extend(probs.cpu().numpy().flatten().tolist())

        # ── Per-batch metrics (not cumulative) ──
        pbar.set_postfix({
            "loss": f"{loss.item():.4f}",
            "acc":  f"{100.*correct/total:.2f}%"
        })

    epoch_loss = running_loss / total
    epoch_acc  = correct / total
    try:
        epoch_f1  = f1_score(all_labels, [p > 0.5 for p in all_probs], zero_division=0)
        epoch_auc = roc_auc_score(all_labels, all_probs) if len(set(all_labels)) > 1 else float("nan")
    except Exception:
        epoch_f1, epoch_auc = 0.0, float("nan")

    print(f"  [Train] loss={epoch_loss:.4f}  acc={100.*epoch_acc:.2f}%  "
          f"F1={epoch_f1:.4f}  AUC={epoch_auc:.4f}")
    return epoch_loss, epoch_acc, epoch_f1, epoch_auc


@torch.no_grad()
def evaluate(model_obj, loader, criterion_obj, device_obj, is_frame_level=False):
    model_obj.eval()
    running_loss = 0.0
    correct = 0
    total   = 0
    all_labels = []
    all_probs  = []

    pbar = tqdm(loader, desc="Evaluating", leave=False)
    for batch in pbar:
        rgb   = batch["rgb"].to(device_obj, non_blocking=True)
        label = batch["label"].to(device_obj, non_blocking=True).unsqueeze(1)

        with autocast('cuda'):
            if is_frame_level:
                S = rgb.shape[1]
                outputs = model_obj(rgb[:, S // 2])
            else:
                fft   = batch["fft"].to(device_obj, non_blocking=True)
                audio = batch["audio"].to(device_obj, non_blocking=True)
                audio_mask = batch.get("audio_missing")
                if audio_mask is not None:
                    audio_mask = audio_mask.to(device_obj, non_blocking=True)
                outputs = model_obj(rgb, fft, audio, audio_mask=audio_mask)

            loss = criterion_obj(outputs, label)

        bs = label.size(0)
        running_loss += loss.item() * bs
        probs  = torch.sigmoid(outputs)
        preds  = (probs > 0.5).float()
        correct += (preds == label).sum().item()
        total   += bs

        all_labels.extend(label.cpu().numpy().flatten().tolist())
        all_probs.extend(probs.cpu().numpy().flatten().tolist())

    val_loss = running_loss / total
    val_acc  = correct / total
    try:
        val_f1  = f1_score(all_labels, [p > 0.5 for p in all_probs], zero_division=0)
        val_auc = roc_auc_score(all_labels, all_probs) if len(set(all_labels)) > 1 else float("nan")
    except Exception:
        val_f1, val_auc = 0.0, float("nan")

    print(f"  [Val]   loss={val_loss:.4f}  acc={100.*val_acc:.2f}%  "
          f"F1={val_f1:.4f}  AUC={val_auc:.4f}")
    return val_loss, val_acc, val_f1, val_auc


